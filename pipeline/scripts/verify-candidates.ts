import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { z } from "zod";
import { loadConfig } from "../src/config";
import { type HttpClient, createHttpClient } from "../src/lib/http";
import {
  type CandidateResult,
  candidateSchema,
  slugFor,
  summarize,
  verifyCandidate,
} from "../src/tools/candidates";

const ROOT = resolve(import.meta.dirname, "../..");
const PAUSE_MS = 1_000;

const sleep = (ms: number) => new Promise((done) => setTimeout(done, ms));

function throttled(http: HttpClient): HttpClient {
  return {
    text: async (url) => {
      await sleep(PAUSE_MS);
      return http.text(url);
    },
    json: async (url, request) => {
      await sleep(PAUSE_MS);
      return http.json(url, request);
    },
  };
}

const LABEL: Record<string, string> = {
  "already-watched": "Already watched",
  confirmed: "Confirmed, has jobs",
  "confirmed-empty": "Confirmed, but 0 jobs right now",
  "exists-unsupported": "Exists on a system we don't support yet (verified)",
  "unverified-unsupported": "Claims a system we can't check yet (Emply, HR Manager, Oracle, …)",
  manual: "Needs a manual look (Workday / SuccessFactors)",
  "not-found": "Not found on any supported portal",
};

function row(r: CandidateResult): string {
  const counts = r.counts ? `${r.counts.jobs} | ${r.counts.inDenmark} | ${r.counts.matches}` : "– | – | –";
  const claim = r.claimCorrect === undefined ? "" : r.claimCorrect ? "✔" : "✘";
  return `| ${r.id} | ${r.name} | ${r.claimed.join(" / ")} | ${r.source ?? ""} ${claim} | ${r.sourceKey ?? ""} | ${counts} | ${r.note ?? ""} |`;
}

function report(results: CandidateResult[], startedAt: Date): string {
  const s = summarize(results);
  const lines = [
    "# Candidate companies: verification report",
    "",
    `Generated by \`pnpm candidates:verify\` on ${startedAt.toISOString().slice(0, 16).replace("T", " ")} UTC from \`config/candidates.json\` (150 companies from the user's list). ${s.requests} requests, one per second.`,
    "",
    "Columns: **jobs** = open jobs on the board; **in DK** = jobs that pass the location rule; **match** = jobs that pass the full filter today. ✔/✘ = whether the list's claimed system was right.",
    "",
    "## Summary",
    "",
    "| Status | Companies |",
    "|---|---|",
    ...Object.entries(LABEL).map(([status, label]) => `| ${label} | ${s.byStatus[status] ?? 0} |`),
    "",
    `Claimed systems checked: ${s.claimsChecked}, correct: ${s.claimsCorrect}.`,
    "",
  ];
  for (const [status, label] of Object.entries(LABEL)) {
    const group = results.filter((r) => r.status === status);
    if (group.length === 0) continue;
    group.sort((a, b) => (b.counts?.matches ?? 0) - (a.counts?.matches ?? 0) || (b.counts?.inDenmark ?? 0) - (a.counts?.inDenmark ?? 0));
    lines.push(`## ${label} (${group.length})`, "", "| # | Company | Claimed | Found | Key | jobs | in DK | match | Note |", "|---|---|---|---|---|---|---|---|---|", ...group.map(row), "");
  }
  return lines.join("\n");
}

function suggestions(results: CandidateResult[]) {
  return results
    .filter((r) => r.status === "confirmed" && (r.counts?.inDenmark ?? 0) > 0 && r.source && r.sourceKey)
    .map((r) => ({
      slug: slugFor(r.name).replace(/(?<=[a-z])(?=[0-9])/g, "-") || `candidate-${r.id}`,
      name: r.name.replace(/\s*\(.*\)\s*$/, "").replace(/ Denmark$/, ""),
      source: r.source,
      sourceKey: r.sourceKey,
      tags: [r.category],
      active: true,
      notes: `Verified ${new Date().toISOString().slice(0, 10)} by candidates:verify: ${r.counts!.jobs} jobs, ${r.counts!.inDenmark} in Denmark, ${r.counts!.matches} matching.`,
    }));
}

async function main(): Promise<void> {
  const startedAt = new Date();
  const candidates = z.array(candidateSchema).parse(JSON.parse(readFileSync(resolve(ROOT, "config/candidates.json"), "utf8")));
  const only = process.argv.slice(2).map(Number).filter(Boolean);
  const todo = only.length > 0 ? candidates.filter((c) => only.includes(c.id)) : candidates;
  const http = throttled(createHttpClient({ userAgent: loadConfig().USER_AGENT, retryDelayMs: 2_000 }));
  const warn = console.warn;
  console.warn = () => {};

  const results: CandidateResult[] = [];
  for (const candidate of todo) {
    const result = await verifyCandidate(candidate, http);
    results.push(result);
    const counts = result.counts ? ` jobs=${result.counts.jobs} dk=${result.counts.inDenmark} match=${result.counts.matches}` : "";
    console.log(`[${results.length}/${todo.length}] #${candidate.id} ${candidate.name}: ${result.status}${result.source ? ` ${result.source}:${result.sourceKey}` : ""}${counts} (${result.requests} req)`);
  }
  console.warn = warn;

  const suggested = suggestions(results);
  if (only.length > 0) {
    console.log("partial run: report files left unchanged");
    console.log(JSON.stringify({ summary: summarize(results), suggested }, null, 2));
    return;
  }
  writeFileSync(resolve(ROOT, "docs/candidates-report.md"), `${report(results, startedAt)}\n`);
  writeFileSync(resolve(ROOT, "config/candidates-suggested.json"), `${JSON.stringify(suggested, null, 2)}\n`);
  console.log(JSON.stringify({ summary: summarize(results), suggested: suggested.length }));
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
