import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { z } from "zod";
import { loadConfig } from "../src/config";
import { type HttpClient, createHttpClient } from "../src/lib/http";
import { candidateSchema, slugFor } from "../src/tools/candidates";
import { type DetectionResult, detectCompany } from "../src/tools/detect";

const ROOT = resolve(import.meta.dirname, "../..");
const PAUSE_MS = 1_000;

const sleep = (ms: number) => new Promise((done) => setTimeout(done, ms));

function throttled(http: HttpClient): HttpClient {
  return {
    text: async (url) => {
      await sleep(PAUSE_MS);
      return http.text(url);
    },
    json: async (url, request) => {
      await sleep(PAUSE_MS);
      return http.json(url, request);
    },
  };
}

const LABEL: Record<DetectionResult["status"], string> = {
  confirmed: "Board found and confirmed, has jobs",
  "confirmed-empty": "Board found and confirmed, 0 jobs right now",
  "found-unverified": "Board found, not verified (Workday, or its check failed)",
  "found-custom": "Own career page with job links (CUSTOM), check by hand",
  unsupported: "Uses a system we can't read yet",
  blocked: "robots.txt forbids reading the careers page",
  "nothing-found": "No job board recognised on the website",
  error: "Website could not be reached",
};

function row(r: DetectionResult): string {
  const counts = r.counts ? `${r.counts.jobs} | ${r.counts.inDenmark} | ${r.counts.matches}` : "– | – | –";
  const others = r.other.map((o) => `${o.system}: ${o.key}`).slice(0, 3).join("<br>");
  return `| ${r.id} | ${r.name} | ${r.website} | ${r.system ?? ""} | ${r.sourceKey ?? ""} | ${counts} | ${others} ${r.note ?? ""} |`;
}

function report(results: DetectionResult[], startedAt: Date): string {
  const requests = results.reduce((n, r) => n + r.requests, 0);
  const counts: Record<string, number> = {};
  for (const r of results) counts[r.status] = (counts[r.status] ?? 0) + 1;
  const unsupported: Record<string, number> = {};
  for (const r of results) {
    for (const system of new Set(r.other.filter((o) => !o.supported).map((o) => o.system))) {
      unsupported[system] = (unsupported[system] ?? 0) + 1;
    }
  }
  const lines = [
    "# Careers-page detection report",
    "",
    `Generated by \`pnpm candidates:detect\` on ${startedAt.toISOString().slice(0, 16).replace("T", " ")} UTC for the candidates that \`candidates:verify\` could not confirm. Each website was read only where robots.txt allows it; ${requests} requests, one per second. Websites were filled in by hand and may be wrong; check the company before adding it.`,
    "",
    "## Summary",
    "",
    "| Result | Companies |",
    "|---|---|",
    ...Object.entries(LABEL).map(([status, label]) => `| ${label} | ${counts[status] ?? 0} |`),
    "",
    `Systems we can't read yet, by number of companies where they were seen: ${Object.entries(unsupported).sort((a, b) => b[1] - a[1]).map(([s, n]) => `${s} ${n}`).join(", ") || "none"}.`,
    "",
  ];
  for (const [status, label] of Object.entries(LABEL)) {
    const group = results.filter((r) => r.status === status);
    if (group.length === 0) continue;
    group.sort((a, b) => (b.counts?.matches ?? 0) - (a.counts?.matches ?? 0) || (b.counts?.inDenmark ?? 0) - (a.counts?.inDenmark ?? 0));
    lines.push(`## ${label} (${group.length})`, "", "| # | Company | Website | System | Key | jobs | in DK | match | Also seen / note |", "|---|---|---|---|---|---|---|---|---|", ...group.map(row), "");
  }
  return lines.join("\n");
}

function suggestions(results: DetectionResult[]) {
  return results
    .filter((r) => r.status === "confirmed" && (r.counts?.inDenmark ?? 0) > 0 && r.system && r.sourceKey)
    .map((r) => ({
      slug: slugFor(r.name) || `candidate-${r.id}`,
      name: r.name.replace(/\s*\(.*\)\s*$/, "").replace(/ Denmark$/, ""),
      source: r.system,
      sourceKey: r.sourceKey,
      careersUrl: r.pages.at(-1) ?? r.website,
      active: true,
      notes: `Detected ${new Date().toISOString().slice(0, 10)} from ${r.website}: ${r.counts!.jobs} jobs, ${r.counts!.inDenmark} in Denmark, ${r.counts!.matches} matching.`,
    }));
}

async function main(): Promise<void> {
  const startedAt = new Date();
  const candidates = z.array(candidateSchema).parse(JSON.parse(readFileSync(resolve(ROOT, "config/candidates.json"), "utf8")));
  const only = process.argv.slice(2).map(Number).filter(Boolean);
  const todo = candidates.filter((c) => (only.length > 0 ? only.includes(c.id) : !c.watchedSlug && !c.verified && c.website));
  const http = throttled(createHttpClient({ userAgent: loadConfig().USER_AGENT, retryDelayMs: 2_000 }));
  const warn = console.warn;
  console.warn = () => {};

  const results: DetectionResult[] = [];
  for (const candidate of todo) {
    const result = await detectCompany(candidate, http);
    results.push(result);
    const counts = result.counts ? ` jobs=${result.counts.jobs} dk=${result.counts.inDenmark} match=${result.counts.matches}` : "";
    const others = result.other.map((o) => o.system).join(",");
    console.log(`[${results.length}/${todo.length}] #${candidate.id} ${candidate.name}: ${result.status}${result.system ? ` ${result.system}:${result.sourceKey}` : ""}${counts}${others ? ` other=${others}` : ""} (${result.requests} req)`);
  }
  console.warn = warn;

  const suggested = suggestions(results);
  if (only.length > 0) {
    console.log("partial run: report files left unchanged");
    console.log(JSON.stringify(suggested, null, 2));
    return;
  }
  writeFileSync(resolve(ROOT, "docs/careers-detection-report.md"), `${report(results, startedAt)}\n`);
  writeFileSync(resolve(ROOT, "config/detected-suggested.json"), `${JSON.stringify(suggested, null, 2)}\n`);
  console.log(JSON.stringify({ results: results.length, suggested: suggested.length }));
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
